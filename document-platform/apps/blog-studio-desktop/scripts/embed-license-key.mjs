// Embeds the license-certificate public key into the desktop build.
// Source: BLOG_STUDIO_LICENSE_PUBLIC_KEY (PEM), or the production API's
// /licenses/certificate-public-key endpoint (APPTOOLKITLAB_API_URL).
import crypto from 'node:crypto';
import fs from 'node:fs';

const apiBaseUrl = (process.env.APPTOOLKITLAB_API_URL || 'https://apptoolkitlab.com/api/v1').replace(/\/$/, '');
let pem = process.env.BLOG_STUDIO_LICENSE_PUBLIC_KEY?.replace(/\\n/g, '\n');
if (!pem) {
  const response = await fetch(`${apiBaseUrl}/licenses/certificate-public-key`, {
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) throw new Error(`Could not fetch the license public key (${response.status}).`);
  pem = (await response.json())?.data?.publicKey;
}
const key = crypto.createPublicKey(pem); // throws on anything that is not a valid key
if (key.asymmetricKeyType !== 'ed25519') throw new Error('The license public key must be Ed25519.');

const target = new URL('../src/license-public-key.cjs', import.meta.url);
fs.writeFileSync(
  target,
  `'use strict';\n\n// Generated by scripts/embed-license-key.mjs — do not edit.\nmodule.exports = ${JSON.stringify(
    key.export({ type: 'spki', format: 'pem' }).toString(),
  )};\n`,
);
console.log('Embedded the license public key into the desktop build.');
